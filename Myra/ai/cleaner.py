"""
Strict data cleaning / anti-spam filter.

Every reply is passed through :func:`clean_text` BEFORE it is sent to Telegram
and BEFORE it is written to MongoDB. Entries that still contain links,
usernames or promotional words are rejected outright so the training set can
never be poisoned by spam generated by the model.
"""

import re

# ── Link / username patterns ────────────────────────────────────────────────
TELEGRAM_LINK_RE = re.compile(
    r"(?:https?://)?(?:t\.me|telegram\.me|telegram\.dog|tlgg\.ru)/(?:\+)?[\w/\-]*",
    re.IGNORECASE,
)
URL_RE = re.compile(
    r"(?:https?://|www\.)\S+|(?<![\w@.])(?:[\w\-]+\.)+(?:com|net|org|in|me|io|xyz|top|site|club|shop|link|info|biz|app)\b(?:/\S*)?",
    re.IGNORECASE,
)
MENTION_RE = re.compile(r"(?<![\w/])@[A-Za-z0-9_]{3,}\b")
EMAIL_RE = re.compile(r"[\w.\-]+@[\w\-]+\.[A-Za-z]{2,}")
HTML_TAG_RE = re.compile(r"</?[A-Za-z][^>]*>")
INVITE_KEYWORD_RE = re.compile(
    r"\b(?:join\s*(?:here|now|this|us|karo)|joinchat|invite\s*link)\b", re.IGNORECASE
)

# ── Promotional blocklist ───────────────────────────────────────────────────
PROMO_PHRASES = (
    "join here", "join now", "join this", "join us", "join karo", "join fast",
    "click here", "click now", "click link", "click below",
    "buy now", "buy here", "order now", "shop now", "purchase now",
    "subscribe", "subscribe now", "subscribe karo",
    "dm me", "pm me", "dm for", "message me for", "inbox me",
    "check bio", "link in bio", "bio link",
    "earn money", "make money", "free recharge", "free gift", "free gifts",
    "limited offer", "special offer", "best offer", "discount",
    "register now", "sign up now", "download now", "install now",
    "visit our", "visit website", "visit site", "our website",
    "whatsapp me", "contact us", "contact me", "call now",
    "follow us", "follow me", "follow karo", "share and win",
    "100% free", "guaranteed earning", "work from home",
    "promo code", "promotion", "advertisement", "sponsor",
    "telegram channel", "telegram group", "join channel", "join group",
    "paid promotion", "rented", "buy followers", "buy subscribers",
)

_PROMO_RE = re.compile(
    "|".join(r"\b" + re.escape(p).replace(r"\ ", r"\s+") + r"\b" for p in PROMO_PHRASES),
    re.IGNORECASE,
)

# Phrases that hint a reply is useless even if technically clean.
_EMPTY_REPLIES = {
    "", ".", "..", "...", "-", "--", "n/a", "na", "none", "null",
    "sorry", "i can't", "i cannot", "as an ai", "i am an ai",
    "i'm an ai", "i am a language model", "i'm a language model",
}

# Sentences reduced to only these words after cleaning are considered junk and
# rejected (they are the leftovers of a stripped promotional message).
_STOPWORDS = {
    "at", "in", "on", "to", "is", "are", "was", "a", "an", "the", "and", "or",
    "of", "for", "me", "my", "i", "you", "by", "with", "from", "so", "as",
    "now", "here", "there", "this", "that", "it", "its", "be", "do", "don",
    "ka", "ki", "ke", "ko", "se", "aur", "hai", "ho", "h", "ok", "okay",
}


def _strip_links(text: str) -> str:
    text = HTML_TAG_RE.sub(" ", text)
    text = TELEGRAM_LINK_RE.sub(" ", text)
    text = URL_RE.sub(" ", text)
    text = EMAIL_RE.sub(" ", text)
    text = MENTION_RE.sub(" ", text)
    return text


def find_violations(text: str) -> list[str]:
    """Return a list of rule names violated by *text* (empty list == clean)."""
    if not text:
        return ["empty"]
    violations = []
    if TELEGRAM_LINK_RE.search(text):
        violations.append("telegram_link")
    if URL_RE.search(text):
        violations.append("url")
    if MENTION_RE.search(text):
        violations.append("mention")
    if EMAIL_RE.search(text):
        violations.append("email")
    if _PROMO_RE.search(text):
        violations.append("promo")
    return violations


def is_clean(text: str, allow_emoji_only: bool = False) -> bool:
    """True when *text* passes every blocklist rule and is worth storing."""
    if not text or not text.strip():
        return False
    stripped = text.strip()
    if stripped.lower().strip(".!? ") in _EMPTY_REPLIES:
        return False
    if not allow_emoji_only and not re.search(r"[A-Za-z\u0900-\u097F]", stripped):
        return False
    return not find_violations(stripped)


def clean_text(text: str, max_length: int = 400) -> str:
    """
    Sanitize a reply.

    1. removes HTML tags, all links, emails and @usernames
    2. drops any line that still contains a promotional phrase
    3. collapses whitespace and trims to *max_length*

    Returns an empty string when nothing usable / non-spam remains.
    """
    if not text:
        return ""

    text = str(text).replace("\r", "\n")
    text = _strip_links(text)

    # Drop promotional lines entirely (salvaging fragments produces junk).
    kept_lines = []
    for line in text.split("\n"):
        line = line.strip()
        if not line:
            continue
        if INVITE_KEYWORD_RE.search(line) or _PROMO_RE.search(line):
            continue
        kept_lines.append(line)

    text = " ".join(kept_lines)
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"\s+([,.!?])", r"\1", text)
    text = text.strip(" \t-–—|")
    text = text.strip()

    # Reject leftovers made of stopwords only (e.g. "at", "in on").
    words = re.findall(r"[A-Za-z\u0900-\u097F]+", text.lower())
    if words and all(word in _STOPWORDS for word in words):
        return ""

    if max_length and len(text) > max_length:
        text = text[:max_length].rsplit(" ", 1)[0].strip(" ,-–—")

    if not is_clean(text, allow_emoji_only=True):
        return ""
    return text


def normalize(text: str) -> str:
    """Normalize a trigger for MongoDB storage / lookup."""
    if not text:
        return ""
    cleaned = clean_text(text, max_length=200)
    if cleaned:
        return cleaned
    # Fall back to a light normalization so triggers are still searchable.
    text = _strip_links(text)
    text = re.sub(r"[^\w\s\u0900-\u097F]", " ", text)
    return re.sub(r"\s+", " ", text).strip().lower()


